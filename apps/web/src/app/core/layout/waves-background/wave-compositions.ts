/** A point of the drawing, in the composition's own units. */
export type Point = readonly [x: number, y: number];

/** One ribbon of the drawing: a band between two curves, crossed by contour lines. */
export interface WaveLayer {
  /** The id of its gradient in the template's <defs>, or null for a ribbon of lines only. */
  readonly fill: string | null;
  /** How far below its bottom curve the filled band reaches. */
  readonly pad: number;
  /** How many contour lines run between its two curves. */
  readonly lines: number;
  /** The contour lines' colour, always `var(--q-waves-…)`, and their width. */
  readonly lineColour: string;
  readonly lineWidth: number;
  /** The upper curve, left to right. */
  readonly top: readonly Point[];
  /** The lower curve, left to right. */
  readonly bottom: readonly Point[];
}

/** A whole drawing, ribbons listed from back to front. */
export interface WaveComposition {
  readonly width: number;
  readonly height: number;
  /** How far around the pointer the waves ripple, in the composition's units. */
  readonly reach: number;
  readonly layers: readonly WaveLayer[];
}

